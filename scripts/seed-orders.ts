import 'dotenv/config';
import dataSource from '../src/infrastructure/database/data-source';

const ORDER_COUNT = 600_000;
const PRODUCT_COUNT = 1_000;
const VARIANTS_PER_PRODUCT = 5;
const VARIANT_COUNT = PRODUCT_COUNT * VARIANTS_PER_PRODUCT;
const SEED_MARKER = 'ORDER_SEED_600K_V1';
const SEED_DESCRIPTION = `Generated by scripts/seed-orders.ts [${SEED_MARKER}]`;
const SEED_SKU_PREFIX = 'ORDERSEED600K';
const EXPECTED_DATABASE = 'checkout_core_db';

async function seedOrders(): Promise<void> {
  if (process.env.NODE_ENV !== 'development') {
    throw new Error('Refusing to seed: NODE_ENV must be "development".');
  }

  if (process.env.DB_NAME !== EXPECTED_DATABASE) {
    throw new Error(`Refusing to seed database "${process.env.DB_NAME}". Expected "${EXPECTED_DATABASE}".`);
  }

  await dataSource.initialize();

  try {
    const databaseRows: Array<{ database_name: string }> = await dataSource.query(
      'SELECT current_database() AS database_name',
    );
    const databaseName = databaseRows[0]?.database_name;

    if (databaseName !== EXPECTED_DATABASE) {
      throw new Error(`Connected to unexpected database "${databaseName}".`);
    }

    const existingSeedRows: Array<{ count: string }> = await dataSource.query(
      'SELECT count(*)::text AS count FROM products WHERE description = $1',
      [SEED_DESCRIPTION],
    );

    if (BigInt(existingSeedRows[0]?.count ?? '0') > 0n) {
      throw new Error(
        `Seed data marker ${SEED_MARKER} already exists. This script is one-time to avoid accidentally adding another 600,000 orders.`,
      );
    }

    console.log(`Seeding ${ORDER_COUNT.toLocaleString()} orders into ${databaseName}...`);
    console.log(
      `Dataset: ${PRODUCT_COUNT.toLocaleString()} products, ${VARIANT_COUNT.toLocaleString()} variants, approximately ${(ORDER_COUNT * 2).toLocaleString()} order items.`,
    );

    await dataSource.transaction(async (manager) => {
      await manager.query(`
        CREATE TEMP TABLE seed_products ON COMMIT DROP AS
        SELECT
          uuid_generate_v4() AS id,
          product_number
        FROM generate_series(1, ${PRODUCT_COUNT}) AS product_series(product_number)
      `);

      await manager.query(
        `
          INSERT INTO products (id, name, description, created_at, updated_at)
          SELECT
            id,
            format('Seed order product %s', product_number),
            $1,
            now(),
            now()
          FROM seed_products
        `,
        [SEED_DESCRIPTION],
      );

      await manager.query(`
        CREATE TEMP TABLE seed_variants ON COMMIT DROP AS
        SELECT
          uuid_generate_v4() AS id,
          products.id AS product_id,
          ((products.product_number - 1) * ${VARIANTS_PER_PRODUCT} + variants.variant_number)::integer AS variant_number,
          format('${SEED_SKU_PREFIX}-%s-%s', lpad(products.product_number::text, 4, '0'), lpad(variants.variant_number::text, 2, '0')) AS sku,
          (ARRAY['XS', 'S', 'M', 'L', 'XL'])[variants.variant_number] AS size,
          (ARRAY['Black', 'White', 'Blue', 'Green', 'Red'])[variants.variant_number] AS color,
          (9900 + ((products.product_number * 97 + variants.variant_number * 31) % 90000))::numeric / 100 AS price
        FROM seed_products AS products
        CROSS JOIN generate_series(1, ${VARIANTS_PER_PRODUCT}) AS variants(variant_number)
      `);

      await manager.query(`
        INSERT INTO product_variants (
          id, product_id, sku, size, color, price, stock, is_active, created_at, updated_at
        )
        SELECT
          id, product_id, sku, size, color, price, 1000000, true, now(), now()
        FROM seed_variants
      `);

      await manager.query(`
        CREATE TEMP TABLE seed_orders ON COMMIT DROP AS
        SELECT
          uuid_generate_v4() AS id,
          order_number,
          CASE
            WHEN order_number % 100 < 5 THEN 'cancelled'
            WHEN order_number % 100 < 25 THEN 'completed'
            ELSE 'pending'
          END AS status,
          (
            now() - interval '730 days'
            + ((order_number::bigint * 7919) % (730::bigint * 24 * 60)) * interval '1 minute'
          ) AS created_at
        FROM generate_series(1, ${ORDER_COUNT}) AS order_series(order_number)
      `);

      await manager.query(`
        CREATE TEMP TABLE seed_order_items ON COMMIT DROP AS
        SELECT
          orders.id AS order_id,
          variants.id AS variant_id,
          format('Seed order product %s', ceil(variants.variant_number::numeric / ${VARIANTS_PER_PRODUCT})) AS product_name,
          variants.sku,
          variants.size,
          variants.color,
          variants.price AS unit_price,
          (1 + ((orders.order_number + lines.line_number) % 5))::integer AS quantity,
          variants.price * (1 + ((orders.order_number + lines.line_number) % 5)) AS line_total,
          orders.created_at
        FROM seed_orders AS orders
        CROSS JOIN LATERAL generate_series(1, 1 + (orders.order_number % 3)) AS lines(line_number)
        JOIN seed_variants AS variants
          ON variants.variant_number = ((orders.order_number * 17 + lines.line_number * 101) % ${VARIANT_COUNT}) + 1
      `);

      await manager.query(`
        INSERT INTO orders (id, status, total_amount, created_at, updated_at, cancelled_at)
        SELECT
          orders.id,
          orders.status,
          totals.total_amount,
          orders.created_at,
          CASE
            WHEN orders.status = 'cancelled' THEN orders.created_at + ((orders.order_number % 48) + 1) * interval '1 hour'
            WHEN orders.status = 'completed' THEN orders.created_at + interval '1 day'
            ELSE orders.created_at
          END,
          CASE
            WHEN orders.status = 'cancelled' THEN orders.created_at + ((orders.order_number % 48) + 1) * interval '1 hour'
            ELSE NULL
          END
        FROM seed_orders AS orders
        JOIN (
          SELECT order_id, sum(line_total)::numeric(12,2) AS total_amount
          FROM seed_order_items
          GROUP BY order_id
        ) AS totals ON totals.order_id = orders.id
      `);

      await manager.query(`
        INSERT INTO order_items (
          order_id, variant_id, product_name, sku, size, color,
          unit_price, quantity, line_total, created_at, updated_at
        )
        SELECT
          order_id, variant_id, product_name, sku, size, color,
          unit_price, quantity, line_total, created_at, created_at
        FROM seed_order_items
      `);
    });

    console.log('Refreshing PostgreSQL table statistics with ANALYZE...');
    await dataSource.query('ANALYZE products');
    await dataSource.query('ANALYZE product_variants');
    await dataSource.query('ANALYZE orders');
    await dataSource.query('ANALYZE order_items');

    const counts: Array<{ table_name: string; row_count: string }> = await dataSource.query(
      `
      SELECT 'orders' AS table_name, count(*)::text AS row_count FROM orders
      WHERE id IN (SELECT DISTINCT order_id FROM order_items WHERE sku LIKE $2)
      UNION ALL
      SELECT 'products', count(*)::text FROM products WHERE description = $1
      UNION ALL
      SELECT 'product_variants', count(*)::text FROM product_variants WHERE sku LIKE $2
      UNION ALL
      SELECT 'order_items', count(*)::text FROM order_items WHERE sku LIKE $2
      ORDER BY table_name
    `,
      [SEED_DESCRIPTION, `${SEED_SKU_PREFIX}-%`],
    );

    console.log('Seed complete. Current table counts:');
    for (const row of counts) {
      console.log(`  ${row.table_name}: ${Number(row.row_count).toLocaleString()}`);
    }
    console.log(`Seed marker: ${SEED_MARKER}`);
    console.log('No application indexes were added. The primary keys and SKU unique constraint remain in place.');
  } finally {
    await dataSource.destroy();
  }
}

void seedOrders().catch((error: unknown) => {
  console.error('Order seed failed:', error);
  process.exitCode = 1;
});
